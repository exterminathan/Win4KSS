using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace Win4K.Core.Media;

/// <summary>Which preview(s) of a clip. Flags, so a request can ask for both.</summary>
[Flags]
public enum PreviewKind
{
    None = 0,

    /// <summary>A 480 px JPEG (occasionally a PNG, see <see cref="PreviewState.FileName"/>) for the grid card.</summary>
    Still = 1,

    /// <summary>A 4 s, 480 px, silent H.264 MP4 played while the pointer is over the card.</summary>
    Hover = 2,

    Both = Still | Hover,
}

public enum PreviewStatus
{
    /// <summary>Not generated, not queued.</summary>
    Missing,

    /// <summary>Queued or being generated.</summary>
    Pending,

    /// <summary>On disk; <see cref="PreviewState.Url"/> serves it.</summary>
    Ready,

    /// <summary>
    /// No still could be made, and no attempt failed as such: the clip has no thumbnail and
    /// ffmpeg is not installed. The UI draws a placeholder tinted with
    /// <see cref="PreviewState.PlaceholderColor"/>. Retried after the failure window.
    /// </summary>
    Placeholder,

    /// <summary>Every route failed. Not retried until <see cref="MediaPreviewOptions.RetryAfter"/> has passed.</summary>
    Failed,

    /// <summary>A hover clip, with ffmpeg not installed. Never generated by this instance.</summary>
    Unavailable,
}

/// <summary>
/// The state of one preview, as the UI sees it.
/// </summary>
/// <param name="Key">The clip key (<see cref="ClipInfo.Key"/>).</param>
/// <param name="Kind"><see cref="PreviewKind.Still"/> or <see cref="PreviewKind.Hover"/>, never both.</param>
/// <param name="FileName">File name inside the previews folder when <see cref="PreviewStatus.Ready"/>, else null.</param>
/// <param name="Version">Changes whenever the file is rewritten; <see cref="Url"/> carries it as <c>?v=</c> for cache-busting.</param>
/// <param name="Source">Where a ready preview came from: "thumbnail", "local", "head" or "remote".</param>
/// <param name="PlaceholderColor">A "#rrggbb" tint for a placeholder card, derived from the clip's category.</param>
public sealed record PreviewState(
    string Key,
    PreviewKind Kind,
    PreviewStatus Status,
    string? FileName,
    long Version,
    string? Source,
    string? Error,
    string PlaceholderColor)
{
    /// <summary>
    /// <c>https://previews.win4k/&lt;file&gt;?v=&lt;version&gt;</c> when ready, else null. Phase E maps that
    /// host onto <see cref="MediaPreviewService.Directory"/> with SetVirtualHostNameToFolderMapping.
    /// </summary>
    public string? Url => Status == PreviewStatus.Ready && FileName is not null
        ? $"https://{MediaPreviewService.VirtualHost}/{FileName}?v={Version}"
        : null;
}

public sealed class PreviewEventArgs(PreviewState state) : EventArgs
{
    public PreviewState State { get; } = state;
}

/// <summary>What this machine can do. Fixed for the life of a <see cref="MediaPreviewService"/>.</summary>
/// <param name="FfmpegAvailable">False → remote thumbnails and placeholders only, no hover clips; the UI should say so.</param>
public sealed record PreviewCapabilities(bool FfmpegAvailable, string? FfmpegPath)
{
    public bool HoverClips => FfmpegAvailable;
}

public sealed record PreviewStats(int Stills, int HoverClips, int Failed, long Bytes, long CapBytes, int Pending);

