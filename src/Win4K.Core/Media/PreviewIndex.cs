/// <summary>One preview file's record in previews/index.json.</summary>
public sealed class PreviewItem
{
    public PreviewStatus Status { get; set; }
    public string? File { get; set; }
    public long Bytes { get; set; }
    public DateTime UpdatedUtc { get; set; }
    public string? Source { get; set; }
    public string? Error { get; set; }
}

/// <summary>Everything stored about one clip's previews.</summary>
public sealed class PreviewRecord
{
    public string Hash { get; set; } = "";
    public DateTime LastAccessUtc { get; set; }
    public PreviewItem? Still { get; set; }
    public PreviewItem? Hover { get; set; }

    [JsonIgnore]
    public long Bytes => (Still?.Status == PreviewStatus.Ready ? Still.Bytes : 0) +
                         (Hover?.Status == PreviewStatus.Ready ? Hover.Bytes : 0);

    public PreviewItem? Get(PreviewKind kind) => kind == PreviewKind.Hover ? Hover : Still;

    public void Set(PreviewKind kind, PreviewItem? item)
    {
        if (kind == PreviewKind.Hover)
            Hover = item;
        else
            Still = item;
    }
}

/// <summary>
/// previews/index.json: status, file, size and last access per clip key. Not thread-safe;
/// <see cref="MediaPreviewService"/> guards it with one lock.
/// </summary>
public sealed class PreviewIndex
{
    public const string FileName = "index.json";

    private static readonly JsonSerializerOptions Options = new()
    {
        WriteIndented = false,
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        PropertyNameCaseInsensitive = true,
        Converters = { new JsonStringEnumConverter() },
        DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,
    };

    public int Version { get; set; } = 1;

    public Dictionary<string, PreviewRecord> Entries { get; set; } = new(StringComparer.Ordinal);

    [JsonIgnore]
    public long TotalBytes => Entries.Values.Sum(e => e.Bytes);

    public PreviewRecord GetOrAdd(string key)
    {
        if (!Entries.TryGetValue(key, out var record))
        {
            record = new PreviewRecord { Hash = HashFor(key) };
            Entries[key] = record;
        }
        return record;
    }

    /// <summary>
    /// Filename-safe, stable stand-in for a clip key: the first 16 hex digits of its SHA-1.
    /// Keys contain ':' and '/', and archive keys run long, so they cannot be file names.
    /// </summary>
    public static string HashFor(string key) =>
        Convert.ToHexString(SHA1.HashData(Encoding.UTF8.GetBytes(key)))[..16].ToLowerInvariant();

    /// <summary>
    /// Keys to evict, least recently accessed first, until the ready files fit in
    /// <paramref name="capBytes"/>. Keys in <paramref name="protect"/> (being generated or
    /// just requested) are never chosen. Pure: changes nothing.
    /// </summary>
    public IReadOnlyList<string> SelectEvictions(long capBytes, IReadOnlySet<string>? protect = null)
    {
        var total = TotalBytes;
        if (total <= capBytes)
            return [];

        var victims = new List<string>();
        foreach (var (key, record) in Entries.Where(e => e.Value.Bytes > 0)
                                             .OrderBy(e => e.Value.LastAccessUtc)
                                             .ThenBy(e => e.Key, StringComparer.Ordinal))
        {
            if (total <= capBytes)
                break;
            if (protect?.Contains(key) == true)
                continue;
            victims.Add(key);
            total -= record.Bytes;
        }
        return victims;
    }

    public static PreviewIndex Load(string path)
    {
        try
        {
            var text = Caching.SharedFile.Read(path);
            if (string.IsNullOrWhiteSpace(text))
                return new PreviewIndex();
            var index = JsonSerializer.Deserialize<PreviewIndex>(text, Options) ?? new PreviewIndex();
            index.Entries = new Dictionary<string, PreviewRecord>(index.Entries ?? [], StringComparer.Ordinal);
            return index;
        }
        catch (Exception ex)
        {
            // Losing the index costs a regeneration, nothing more.
            Log.Warn($"Previews: index unreadable, starting empty: {ex.Message}");
            return new PreviewIndex();
        }
    }

    public string Serialize() => JsonSerializer.Serialize(this, Options);
}
